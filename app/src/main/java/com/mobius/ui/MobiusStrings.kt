/**
 * v7 — LANGUAGE (Bahasa Indonesia + English).
 *
 * Central strings table (NOT Android string resources): the app has two
 * composition roots — the launcher Activity AND the bubble Service — and
 * both must read the SAME setting without any locale machinery. A DataStore
 * value + a CompositionLocal does that with one code path for both roots;
 * changing the language recomposes both roots immediately (no restart,
 * no reinstall).
 *
 * Default: Bahasa Indonesia (Tuan's language). Proper nouns, package names,
 * model names (Gemini, Nano) and the tagline are never translated.
 *
 * BOUNDARY (honest): only STATIC UI chrome is translated. Dynamic messages
 * generated by the core/AI (task statuses, outcomes, routing-log reasons,
 * skill names, step text) stay in the language the core produced them in —
 * translating those would mean touching Orchestrator/AIRouter/agents.
 */
enum class AppLanguage { ID, EN }

private val Context.appLanguageDataStore: DataStore<Preferences> by preferencesDataStore(name = "app_language")

/** Persists the UI language (same DataStore pattern as the feature flags). */
class LanguageManager(context: Context) {
    private val store = context.applicationContext.appLanguageDataStore

    val language: Flow<AppLanguage> = store.data.map { prefs ->
        when (prefs[stringPreferencesKey("language")]) {
            "en" -> AppLanguage.EN
            else -> AppLanguage.ID
        }
    }

    suspend fun setLanguage(lang: AppLanguage) {
        store.edit { it[stringPreferencesKey("language")] = if (lang == AppLanguage.EN) "en" else "id" }
    }
}

/** Provided at both composition roots (MobiusRoot + BubbleService hosts). */
